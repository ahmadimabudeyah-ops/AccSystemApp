def wipe(tid: str) -> None:
    """Delete every transactional row for this tenant, in child -> parent order.

    The DELETE statements are written to a temp SQL file and executed by the
    migration helper (scripts/_sqlrun.py) under the DB owner role, because the
    immutability triggers (fn_forbid_posted_*) cannot be suspended by the
    application role.  The demo dataset that follows is rebuilt through the real
    service layer, so the resulting data is produced by exactly the same audit
    path a client uses.
    """
    import subprocess
    import tempfile
    lines = ["BEGIN;", "SET session_replication_role = replica;"]
    for t in WIPE:
        lines.append(f"DELETE FROM {t} WHERE tenant_id = '{tid}';")
    lines.append("DELETE FROM doc_sequences WHERE tenant_id = '" + tid + "';")
    lines.append("COMMIT;")
    with tempfile.NamedTemporaryFile("w", suffix=".sql", delete=False,
                                     encoding="utf-8") as fh:
        fh.write("\n".join(lines))
        path = fh.name
    helper = os.path.join(os.path.dirname(__file__), "_sqlrun.py")
    r = subprocess.run([sys.executable, helper, path], capture_output=True, text=True)
    os.unlink(path)
    if r.returncode != 0:
        raise SystemExit(f"wipe failed: {r.stdout[-600:]} {r.stderr[-600:]}")


def main() -> None:
    app = create_app()
    with app.app_context():
        trow = db.session.execute(text("SELECT id FROM tenants WHERE code='DEMO'")).first()
        if not trow:
            print("tenant DEMO not found — run seed_base first")
            return 1
        tid = str(trow[0])
        db.session.execute(text("SET app.current_tenant_id = :t"), {"t": tid})
        erow = db.session.execute(text(
            "SELECT id FROM entities WHERE tenant_id=:t AND code='MAIN'"), {"t": tid}).first()
        eid = str(erow[0])

        if KEEP:
            print("KEEP-TRANSACTIONS: nothing wiped")
        else:
            db.session.execute(text("SET app.current_tenant_id = :t"), {"t": tid})
            wipe(tid)
            db.session.commit()
            print("WIPED transactional tables")

        # reset balance cache so reports recompute from journal_lines
        if not KEEP:
            try:
                db.session.execute(text(
                    "DELETE FROM account_balances_cache WHERE entity_id=:e"), {"e": eid})
                db.session.commit()
            except Exception:
                db.session.rollback()
        print(f"OK tenant={tid} entity={eid}")
        print("NEXT: run scripts/seed_demo_full.py")
    return 0


if __name__ == "__main__":
    sys.exit(main() or 0)
